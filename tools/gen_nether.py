import sys, re
sys.path.insert(0,'.')
from cpp2rs import *
src=open('/mnt/user-data/uploads/MinecraftConsoles-main/Minecraft.World/NetherBridgePieces.cpp').read()
tiles=set(re.findall(r'pub const (\w+): i32', open('../mc-rs/mc-worldgen/src/structure/ti.rs').read()))
classes={ # C++ class: (rust fn, W,H,D, fields)
 'BridgeStraight':('bridge_straight',5,10,19,[]),
 'BridgeCrossing':('bridge_crossing',19,10,19,[]),
 'RoomCrossing':('room_crossing',7,9,7,[]),
 'StairsRoom':('stairs_room',7,11,7,[]),
 'MonsterThrone':('monster_throne',7,8,9,['hasPlacedMobSpawner']),
 'CastleEntrance':('castle_entrance',13,14,13,[]),
 'CastleStalkRoom':('castle_stalk_room',13,14,13,[]),
 'CastleSmallCorridorPiece':('small_corridor',5,7,5,[]),
 'CastleSmallCorridorCrossingPiece':('small_corridor_crossing',5,7,5,[]),
 'CastleSmallCorridorRightTurnPiece':('small_corridor_right_turn',5,7,5,['isNeedingChest']),
 'CastleSmallCorridorLeftTurnPiece':('small_corridor_left_turn',5,7,5,['isNeedingChest']),
 'CastleCorridorStairsPiece':('corridor_stairs',5,14,10,[]),
 'CastleCorridorTBalconyPiece':('corridor_t_balcony',9,7,9,[]),
}
out='''//! GENERATED by tools/gen_nether.py from `NetherBridgePieces.cpp` (the `postProcess` bodies). Do not edit by hand.
#![allow(non_snake_case, unused_mut, unused_variables, unused_assignments, unused_parens, clippy::all)]
use super::ctx::*;
use super::nether_bridge::*;
use super::*;
use std::cmp::{max, min};
'''
def cut_block(b, start_pat, repl):
    i=b.index(start_pat)
    j=b.index('{',i)
    d=0;k=j
    while True:
        if b[k]=='{': d+=1
        elif b[k]=='}':
            d-=1
            if d==0: break
        k+=1
    return b[:i]+repl+b[k+1:]
for cls,(fn,W,H,D,fields) in classes.items():
    b=extract_function(src, r'bool NetherBridgePieces::%s::postProcess\(Level \*level, Random \*random, BoundingBox \*chunkBB\)'%cls)
    b=b.replace('WeighedTreasureArray(fortressTreasureItems,FORTRESS_TREASURE_ITEMS_COUNT)','FORTRESSITEMS')
    b=b.replace('level->setInstaTick(true);','LAVAON();').replace('level->setInstaTick(false);','LAVAOFF();')
    b=b.replace('Tile::tiles[Tile::lava_Id]->tick(level, x, y, z, random);','LAVATICK(x, y, z);')
    if cls=='MonsterThrone':
        b=cut_block(b,'if (!hasPlacedMobSpawner)','THRONESPAWN();')
    t=T(fields=fields, consts={'width':'W','height':'H','depth':'D'}, known_tiles=tiles)
    r=finish(t.stmt_lines(b))
    if t.unknown_tiles: print(cls,'UNKNOWN',sorted(t.unknown_tiles),file=sys.stderr)
    r=r.replace('self.','p.').replace('~','!')
    r=r.replace('FORTRESSITEMS','&fortress_treasure()').replace('LAVAON();','c.lv.insta_tick = true;').replace('LAVAOFF();','c.lv.insta_tick = false;')
    r=re.sub(r'LAVATICK\((.*?)\);',lambda m:'c.lv.tick_tile(%s, ti::LAVA as u8, c.rnd);'%m.group(1),r)
    r=r.replace('THRONESPAWN();','p.throne_spawn(c);')
    out+='\npub fn post_process_%s(p: &mut NPiece, c: &mut Ctx) -> bool {\n    const W: i32 = %d;\n    const H: i32 = %d;\n    const D: i32 = %d;\n    let _ = (W, H, D);\n'%(fn,W,H,D)
    out+=r+'\n}\n'
open('../mc-rs/mc-worldgen/src/structure/nether_bridge_gen.rs','w').write(out)
print(len(out))
