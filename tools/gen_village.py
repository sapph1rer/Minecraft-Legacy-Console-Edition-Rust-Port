import sys, re
sys.path.insert(0,'.')
from cpp2rs import *
src=open('/mnt/user-data/uploads/MinecraftConsoles-main/Minecraft.World/VillagePieces.cpp').read()
tiles=set(re.findall(r'pub const (\w+): i32', open('../mc-rs/mc-worldgen/src/structure/ti.rs').read()))
alias={'stairs_wood':'STAIRS_WOOD'}
classes={ # name: (fn, W,H,D, fields)
 'Well':('well',6,15,6,['heightPosition']),
 'SimpleHouse':('simple_house',5,6,5,['heightPosition','hasTerrace']),
 'SmallTemple':('small_temple',5,12,9,['heightPosition']),
 'BookHouse':('book_house',9,9,6,['heightPosition']),
 'SmallHut':('small_hut',4,6,5,['heightPosition','lowCeiling','tablePlacement']),
 'PigHouse':('pig_house',9,7,11,['heightPosition']),
 'TwoRoomHouse':('two_room_house',9,7,12,['heightPosition']),
 'Smithy':('smithy',10,6,7,['heightPosition','hasPlacedChest']),
 'Farmland':('farmland',7,4,9,['heightPosition','cropsA','cropsB']),
 'DoubleFarmland':('double_farmland',13,4,9,['heightPosition','cropsA','cropsB','cropsC','cropsD']),
 'LightPost':('light_post',3,4,2,['heightPosition']),
}
out='''//! GENERATED by tools/cpp2rs.py from `VillagePieces.cpp` (the `postProcess` bodies). Do not edit by hand.
#![allow(non_snake_case, unused_mut, unused_variables, unused_assignments, clippy::all)]
use super::ctx::*;
use super::village::VPiece;
use super::*;
'''
for cls,(fn,W,H,D,fields) in classes.items():
    b=extract_function(src, r'bool VillagePieces::%s::postProcess\(Level \*level, Random \*random, BoundingBox \*chunkBB\)'%cls)
    t=T(fields=fields, consts={'width':'W','height':'H','depth':'D','treasureItems':'&super::village::smithy_treasure()'},
        known_tiles=tiles)
    t.tile_alias={'wool':'WOOL','stairs_wood':'STAIRS_WOOD','pressurePlate_wood':'PRESSURE_PLATE_WOOD','workBench':'WORK_BENCH','ironFence':'IRON_FENCE','thinGlass':'THIN_GLASS'}
    body=b.replace('DyePowderItem::WHITE','15').replace('Mth::nextInt(random,','Mth::nextInt(random,')
    r=finish(t.stmt_lines(body))
    if t.unknown_tiles: print(cls,'UNKNOWN',sorted(t.unknown_tiles),file=sys.stderr)
    out+='\npub fn post_process_%s(p: &mut VPiece, c: &mut Ctx) -> bool {\n    const W: i32 = %d;\n    const H: i32 = %d;\n    const D: i32 = %d;\n    let _ = (W, H, D);\n'%(fn,W,H,D)
    out+=r.replace('self.','p.')+'\n}\n'
open('../mc-rs/mc-worldgen/src/structure/village_gen.rs','w').write(out)
print(len(out))
