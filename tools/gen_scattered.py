import sys, re
sys.path.insert(0,'.')
from cpp2rs import *
src=open('/mnt/user-data/uploads/MinecraftConsoles-main/Minecraft.World/ScatteredFeaturePieces.cpp').read()
tiles=set(re.findall(r'pub const (\w+): i32', open('../mc-rs/mc-worldgen/src/structure/ti.rs').read()))
classes={'DesertPyramidPiece':('desert_pyramid',21,15,21),'JunglePyramidPiece':('jungle_pyramid',12,10,15),'SwamplandHut':('swamp_hut',7,5,9)}
REPL=[('SandStoneTile::TYPE_SMOOTHSIDE','2'),('SandStoneTile::TYPE_HEIROGLYPHS','1'),('StoneSlabTile::SAND_SLAB','1'),
 ('TreeTile::DARK_TRUNK','1'),('SmoothStoneBrickTile::TYPE_DETAIL','3'),('TripWireSourceTile::MASK_ATTACHED','4'),
 ('TripWireTile::MASK_ATTACHED','4'),('FlowerPotTile::TYPE_MUSHROOM_RED','7'),('StairTile::DIR_NORTH','3'),('StairTile::DIR_SOUTH','2'),
 ('StairTile::DIR_EAST','0'),('StairTile::DIR_WEST','1'),('DyePowderItem::ORANGE','14'),('DyePowderItem::BLUE','4'),
 ('LeverTile::getLeverFacing','lever_facing'),('Direction::STEP_X','DIR_STEP_X'),('Direction::STEP_Z','DIR_STEP_Z'),
 ('WeighedTreasureArray(dispenserItems,DISPENSER_ITEMS_COUNT)','DISPENSERITEMS'),
 ('&stoneSelector','MOSSSEL')]
BOOK=re.compile(r'WeighedTreasure::addToTreasure\(WeighedTreasureArray\(treasureItems,TREASURE_ITEMS_COUNT\), Item::enchantedBook->createForRandomTreasure\(random\)\)')
out='''//! GENERATED by tools/gen_scattered.py from `ScatteredFeaturePieces.cpp` (the `postProcess` bodies). Do not edit by hand.
#![allow(non_snake_case, unused_mut, unused_variables, unused_assignments, unused_parens, clippy::all)]
use super::ctx::*;
use super::scattered::*;
use super::*;
'''
for cls,(fn,W,H,D) in classes.items():
    b=extract_function(src, r'bool ScatteredFeaturePieces::%s::postProcess\(Level \*level, Random \*random, BoundingBox \*chunkBB\)'%cls)
    for a,r in REPL: b=b.replace(a,r)
    b=BOOK.sub('TBOOK',b)
    b=re.sub(r'hasPlacedChest\[i\]','HPC_i',b)
    b=b.replace('updateAverageGroundHeight(level, chunkBB, 0)','updateAverageGroundHeight(0)')
    if cls=='SwamplandHut':
        i=b.index('if (!spawnedWitch)'); j=b.rindex('return true;')
        b=b[:i]+'WITCHSPAWN();\n\t'+b[j:]
    fields={'placedMainChest':0,'placedHiddenChest':0,'placedTrap1':0,'placedTrap2':0}
    t=T(fields=list(fields) if cls=='JunglePyramidPiece' else [], consts={'width':'W','height':'H','depth':'D','treasureItems':'TREASUREITEMS'},known_tiles=tiles,
        selectors={'MOSSSEL':'moss_selector'})
    t.tile_alias={'stairs_sprucewood':'STAIRS_SPRUCEWOOD','stairs_sandstone':'STAIRS_SANDSTONE','stairs_stone':'STAIRS_STONE','stairs_wood':'STAIRS_WOOD','stoneSlabHalf':'STONE_SLAB_HALF','pressurePlate_stone':'PRESSURE_PLATE_STONE','diode_off':'DIODE_OFF','pistonStickyBase':'PISTON_STICKY_BASE','redStoneDust':'RED_STONE_DUST','tripWireSource':'TRIP_WIRE_SOURCE','tripWire':'TRIP_WIRE'}
    r=finish(t.stmt_lines(b))
    if t.unknown_tiles: print(cls,'UNKNOWN',sorted(t.unknown_tiles),file=sys.stderr)
    # post fixups
    lines=[]
    r=r.replace('~','!')
    for ln in r.replace('self.','p.').split('\n'):
        pre=''
        if 'TBOOK' in ln:
            pre='let tb = pyramid_treasure_with_book(c.rnd); '
            ln=ln.replace('TBOOK','&tb')
        ln=ln.replace('DISPENSERITEMS','&dispenser_items()')
        ln=re.sub(r'HPC_i','p.has_placed_chest[i as usize]',ln)
        ln=ln.replace('WITCHSPAWN();','p.spawn_witch(c);')
        lines.append(pre+ln)
    r='\n'.join(lines)
    out+='\npub fn post_process_%s(p: &mut SPiece, c: &mut Ctx) -> bool {\n    const W: i32 = %d;\n    const H: i32 = %d;\n    const D: i32 = %d;\n    let _ = (W, H, D);\n'%(fn,W,H,D)
    out+=r+'\n}\n'
open('../mc-rs/mc-worldgen/src/structure/scattered_gen.rs','w').write(out)
print(len(out))
